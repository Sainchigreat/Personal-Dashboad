// Generates a compact, versioned, additive SQL reconciliation for ONE verified
// owner, derived from server/personalPlan.ts. Output:
// supabase/migrations/20261102000700_personal_owner_reconcile.sql
// The recurring routine is stored once in settings.daily_templates and expanded
// in SQL, so the migration stays small and never duplicates plan data.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  PERSONAL_ROUTINE,
  PERSONAL_WEEKDAY_PLAN,
  PERSONAL_MONTHLY_GOALS,
  PERSONAL_WEEKLY_GOALS,
  OBSOLETE_TITLES,
  type PlanTask,
} from "../server/personalPlan";

const OWNER_ID = "6d8e45af-5bb3-4e40-adb3-e605b9972c79"; // verified Chisom account
const DAYS = ["2026-11-02", "2026-11-03"];
const WEEKDAYS: Record<string, number> = { "2026-11-02": 1, "2026-11-03": 2 };
const q = (value: string) => `'${String(value).replaceAll("'", "''")}'`;

const goalOutcome: Record<string, string> = Object.fromEntries(
  PERSONAL_WEEKLY_GOALS.map((g) => [g.key, g.outcome]),
);
const monthlyTitle: Record<string, string> = Object.fromEntries(
  PERSONAL_MONTHLY_GOALS.map((g) => [g.key, g.title]),
);

// Compact month/week goal rows.
const monthlyValues = PERSONAL_MONTHLY_GOALS.map(
  (g) =>
    `  (${q(g.title)},${q(g.metric_type)},${q(g.source)},${g.target},${q(g.unit)})`,
).join(",\n");
const weeklyValues = PERSONAL_WEEKLY_GOALS.map(
  (g) =>
    `  (${q(g.outcome)},${g.target},${q(g.unit)},${q(g.source)},${q(monthlyTitle[g.monthlyKey] || "")})`,
).join(",\n");

// Weekday-specific scheduled work for the two already-generated days.
type Row = {
  day: string;
  title: string;
  category: string;
  priority: string;
  minutes: number;
  outcome: string | null;
};
const weekdayRows: Row[] = [];
for (const day of DAYS) {
  for (const task of PERSONAL_WEEKDAY_PLAN[WEEKDAYS[day]] || []) {
    weekdayRows.push({
      day,
      title: task.title,
      category: task.category,
      priority: task.priority,
      minutes: task.estimated_minutes,
      outcome: task.goalKey ? goalOutcome[task.goalKey] || null : null,
    });
  }
}
// A compact plan for each day: weekday-specific work + the recurring routine,
// with its goal key carried through so tasks link to weekly goals.
const allTaskRows: Array<Row & { ord: number }> = [];
for (const day of DAYS) {
  let ord = 0;
  for (const task of [
    ...(PERSONAL_WEEKDAY_PLAN[WEEKDAYS[day]] || []),
    ...(PERSONAL_ROUTINE as PlanTask[]),
  ]) {
    allTaskRows.push({
      day,
      title: task.title,
      category: task.category,
      priority: task.priority,
      minutes: task.estimated_minutes,
      outcome: task.goalKey ? goalOutcome[task.goalKey] || null : null,
      ord: ord++,
    });
  }
}
const taskValues = allTaskRows
  .map(
    (r) =>
      `  (${q(r.day)},${q(r.title)},${q(r.category)},${q(r.priority)},${r.minutes},${r.outcome ? q(r.outcome) : "null"},${r.ord})`,
  )
  .join(",\n");
const obsoleteValues = OBSOLETE_TITLES.map((t) => `  (${q(t)})`).join(",\n");

const routineJson = q(JSON.stringify(PERSONAL_ROUTINE));

const sql = `-- Momentum OS — owner-scoped personal workspace reconciliation.
-- Generated by scripts/build-personal-reconcile-sql.ts from server/personalPlan.ts.
-- Additive: no DROP / TRUNCATE / DELETE. Superseded goals and obsolete TODO
-- tasks are archived / cancelled (status change) so history is preserved.
-- Scoped to exactly one verified owner: ${OWNER_ID}

create table if not exists momentum_os.personal_plan_owner (
  user_id text PRIMARY KEY REFERENCES momentum_os.users(id) ON DELETE CASCADE,
  marked_at text NOT NULL
);
alter table momentum_os.speakers add column if not exists reminder_status text NOT NULL DEFAULT 'not_sent';
alter table momentum_os.speakers add column if not exists asset_approval_status text NOT NULL DEFAULT 'pending';

insert into momentum_os.personal_plan_owner(user_id,marked_at)
values (${q(OWNER_ID)}, now()::text) on conflict do nothing;

update momentum_os.settings
set daily_templates = ${routineJson}, auto_plan = 1, updated_at = now()::text
where user_id = ${q(OWNER_ID)};

update momentum_os.cycles
set sales_target = 68, revenue_target = 1000000, outreach_target = 20,
    status = 'active', updated_at = now()::text
where user_id = ${q(OWNER_ID)} and month = '2026-11';

-- Five monthly goals (old superseded rows are archived, never deleted).
update momentum_os.monthly_goals set status='archived', updated_at=now()::text
where user_id=${q(OWNER_ID)} and status <> 'archived' and title not in (
  ${PERSONAL_MONTHLY_GOALS.map((g) => q(g.title)).join(",\n  ")}
);
with m(title,metric_type,source,target,unit) as (values
${monthlyValues}
)
insert into momentum_os.monthly_goals
  (id,user_id,workspace_id,title,description,category,metric_type,source,target,unit,baseline,status,start_date,end_date,notes,created_at,updated_at)
select 'mg-' || md5(${q(OWNER_ID)} || ':' || m.title), ${q(OWNER_ID)}, 'personal',
  m.title, '', 'November operating plan', m.metric_type, m.source, m.target, m.unit,
  0, 'active', '2026-11-01', '2026-11-30', '', now()::text, now()::text
from m on conflict do nothing;

update momentum_os.weekly_goals set status='archived', updated_at=now()::text
where user_id=${q(OWNER_ID)} and week_start='2026-11-02' and status <> 'archived' and outcome not in (
  ${PERSONAL_WEEKLY_GOALS.map((g) => q(g.outcome)).join(",\n  ")}
);
with w(outcome,target,unit,source,monthly_title) as (values
${weeklyValues}
)
insert into momentum_os.weekly_goals
  (id,user_id,workspace_id,monthly_goal_id,cycle_id,week_start,week_end,outcome,target,unit,current,source,owner_id,assignee_id,priority,status,visibility,notes,created_at,updated_at)
select 'wg-' || md5(${q(OWNER_ID)} || ':' || w.outcome), ${q(OWNER_ID)}, 'personal',
  'mg-' || md5(${q(OWNER_ID)} || ':' || w.monthly_title), null,
  '2026-11-02', '2026-11-08', w.outcome, w.target, w.unit, 0, w.source,
  ${q(OWNER_ID)}, null, 'high', 'active', 'private', '', now()::text, now()::text
from w
on conflict (user_id,week_start,outcome) do update set
  status='active', target=excluded.target, unit=excluded.unit, source=excluded.source,
  monthly_goal_id=excluded.monthly_goal_id, updated_at=excluded.updated_at;

-- Cancel obsolete TODO work only; completed history is untouched.
update momentum_os.tasks set status='cancelled', updated_at=now()::text
where user_id=${q(OWNER_ID)} and status='todo' and title in (
${obsoleteValues}
);

-- Fill the correct plan for days already generated (idempotent, no duplicates).
with p(day,title,category,priority,minutes,outcome,ord) as (values
${taskValues}
)
insert into momentum_os.tasks
  (id,user_id,cycle_id,weekly_goal_id,title,category,priority,status,due_date,scheduled_time,estimated_minutes,sort_order,created_at,updated_at)
select gen_random_uuid()::text, ${q(OWNER_ID)},
  (select id from momentum_os.cycles where user_id=${q(OWNER_ID)} and month='2026-11' limit 1),
  (select id from momentum_os.weekly_goals where user_id=${q(OWNER_ID)} and week_start='2026-11-02' and outcome=p.outcome and status='active' limit 1),
  p.title, p.category, p.priority, 'todo', p.day, '', p.minutes, p.ord, now()::text, now()::text
from p
where not exists (
  select 1 from momentum_os.tasks x
  where x.user_id=${q(OWNER_ID)} and x.due_date=p.day and x.title=p.title
);

-- Link remaining active tasks whose titles map unambiguously to a weekly goal.
update momentum_os.tasks x set weekly_goal_id = g.id, updated_at=now()::text
from momentum_os.weekly_goals g
where x.user_id=${q(OWNER_ID)} and g.user_id=${q(OWNER_ID)}
  and g.week_start='2026-11-02' and g.status='active'
  and x.status <> 'cancelled' and x.weekly_goal_id is null
  and ((x.title like '%course promotion%' and g.outcome like '%course promotion%')
    or (x.title like '%warm leads%' and g.outcome like '%course promotion%')
    or (x.title like '%promotional partners%' and g.outcome like '%promotional partners%'));

-- Fixed Monday–Sunday publishing calendar lives in server/personalPlan.ts
-- (PUBLISHING_CALENDAR) and is used by the date-aware planner.

-- Rollback notes: restore archived goal statuses and cancelled task statuses
-- from a backup; no row is physically removed by this migration.
`;

const out = resolve(
  process.cwd(),
  "supabase/migrations/20261102000700_personal_owner_reconcile.sql",
);
writeFileSync(out, sql);
console.log(`Wrote ${out} (${sql.length} bytes, ${allTaskRows.length} plan rows)`);
